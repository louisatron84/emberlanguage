"""Turns a checked program into one self-contained C file.

The runtime (ember_runtime.h) is pasted at the top, so gcc needs nothing but this file. Names are
prefixed (`v_` for variables, `ember_fn_` for functions) so an Ember name can never clash with a C
keyword or library function. `#line` markers point gcc and debuggers back at the .em source.
"""

from pathlib import Path

from ember import ast
from ember.checker import Checked

C_TYPES = {"int": "int64_t", "float": "double", "bool": "bool", "str": "ember_str", "void": "void"}
RUNTIME = (Path(__file__).parent / "ember_runtime.h").read_text(encoding="utf-8")

INT_OPS = {"+": "ember_add", "-": "ember_sub", "*": "ember_mul", "%": "ember_mod"}
SIMPLE_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\t": "\\t", "?": "\\?"}


def generate(checked: Checked, filename: str) -> str:
    return _Generator(checked, filename).run()


def c_string(text: str) -> tuple[str, int]:
    """The body of a C string literal for `text` (UTF-8), and its length in bytes."""
    data = text.encode("utf-8")
    parts = []
    for byte in data:
        char = chr(byte)
        if char in SIMPLE_ESCAPES:
            parts.append(SIMPLE_ESCAPES[char])
        elif 32 <= byte < 127:
            parts.append(char)
        else:
            parts.append(f"\\{byte:03o}")  # always three digits, so a following digit isn't swallowed
    return "".join(parts), len(data)


class _Generator:
    def __init__(self, checked: Checked, filename: str):
        self.checked = checked
        self.filename = filename
        self.file_literal = c_string(filename)[0]
        self.lines: list[str] = []
        self.depth = 0
        self.temps = 0
        self.returns = "void"

    def emit(self, text: str) -> None:
        self.lines.append("    " * self.depth + text)

    def mark(self, line: int) -> None:
        self.lines.append(f'#line {line} "{self.file_literal}"')

    def type_of(self, node) -> str:
        return self.checked.type_of(node)

    # ---- program and functions -----------------------------------------------------------------

    def run(self) -> str:
        self.lines += [f"/* Generated by the Ember compiler from {self.filename}. Do not edit. */", RUNTIME, ""]
        functions = self.checked.program.functions
        for fn in functions:
            self.emit(self.header(fn) + ";")
        for fn in functions:
            self.emit("")
            self.function(fn)
        self.lines += [
            "",
            "int main(void) {",
            f'    ember_file = "{self.file_literal}";',
            "    ember_fn_main();",
            "    return 0;",
            "}",
            "",
        ]
        return "\n".join(self.lines)

    def header(self, fn: ast.FnDef) -> str:
        signature = self.checked.functions[fn.name]
        params = ", ".join(f"{C_TYPES[t]} v_{p.name}" for p, t in zip(fn.params, signature.params)) or "void"
        return f"static {C_TYPES[signature.returns]} ember_fn_{fn.name}({params})"

    def function(self, fn: ast.FnDef) -> None:
        self.returns = self.checked.functions[fn.name].returns
        self.mark(fn.span.line)
        self.emit(self.header(fn) + " {")
        self.block(fn.body)
        self.emit("}")

    # ---- statements ----------------------------------------------------------------------------

    def block(self, statements) -> None:
        self.depth += 1
        for statement in statements:
            self.mark(statement.span.line)
            self.statement(statement)
        self.depth -= 1

    def statement(self, stmt: ast.Stmt) -> None:
        match stmt:
            case ast.Declare(name, _, value):
                self.emit(f"{C_TYPES[self.type_of(value)]} v_{name} = {self.expr(value)};")
            case ast.Assign(name, value):
                self.emit(f"v_{name} = {self.convert(value, self.type_of(stmt))};")
            case ast.ExprStmt(expr):
                self.emit(f"{self.expr(expr)};")
            case ast.Return(None):
                self.emit("return;")
            case ast.Return(value):
                self.emit(f"return {self.convert(value, self.returns)};")
            case ast.If(branches, else_body):
                for i, (condition, body) in enumerate(branches):
                    opener = "if" if i == 0 else "} else if"
                    self.emit(f"{opener} ({self.expr(condition)}) {{")
                    self.block(body)
                if else_body is not None:
                    self.emit("} else {")
                    self.block(else_body)
                self.emit("}")
            case ast.While(condition, body):
                self.emit(f"while ({self.expr(condition)}) {{")
                self.block(body)
                self.emit("}")
            case ast.For(var, start, end, body):
                # The range is worked out once, before the loop starts; the end is excluded.
                n = self.temps
                self.temps += 1
                self.emit("{")
                self.depth += 1
                self.emit(f"int64_t start_{n} = {self.expr(start)};")
                self.emit(f"int64_t end_{n} = {self.expr(end)};")
                self.emit(f"for (int64_t v_{var} = start_{n}; v_{var} < end_{n}; v_{var}++) {{")
                self.block(body)
                self.emit("}")
                self.depth -= 1
                self.emit("}")

    # ---- expressions ---------------------------------------------------------------------------

    def convert(self, expr: ast.Expr, target: str) -> str:
        """The C for `expr`, widened to a double when a whole number goes where a float is wanted."""
        code = self.expr(expr)
        if target == "float" and self.type_of(expr) == "int":
            return f"((double){code})"
        return code

    def expr(self, expr: ast.Expr) -> str:
        line = expr.span.line
        match expr:
            case ast.IntLit(value):
                return f"INT64_C({value})"
            case ast.FloatLit(value):
                return repr(value)
            case ast.StrLit(value):
                body, length = c_string(value)
                return f'ember_str_lit("{body}", {length})'
            case ast.BoolLit(value):
                return "true" if value else "false"
            case ast.Name(name):
                return f"v_{name}"
            case ast.Unary("not", operand):
                return f"(!{self.expr(operand)})"
            case ast.Unary("-", operand):
                if self.type_of(operand) == "int":
                    return f"ember_neg({self.expr(operand)}, {line})"
                return f"(-{self.expr(operand)})"
            case ast.Binary():
                return self.binary(expr)
            case ast.Call():
                return self.call(expr)
            case ast.Index(target, index):
                return f"ember_str_at({self.expr(target)}, {self.expr(index)}, {line})"
        raise TypeError(f"unknown expression {expr!r}")

    def binary(self, expr: ast.Binary) -> str:
        op, left, right, line = expr.op, expr.left, expr.right, expr.span.line
        left_type, right_type = self.type_of(left), self.type_of(right)
        if op in ("and", "or"):
            return f"({self.expr(left)} {'&&' if op == 'and' else '||'} {self.expr(right)})"
        if left_type == right_type == "str":
            l, r = self.expr(left), self.expr(right)
            if op == "+":
                return f"ember_concat({l}, {r})"
            if op == "==":
                return f"ember_str_eq({l}, {r})"
            if op == "!=":
                return f"(!ember_str_eq({l}, {r}))"
            return f"(ember_str_cmp({l}, {r}) {op} 0)"
        if op == "/":
            return f"ember_div({self.convert(left, 'float')}, {self.convert(right, 'float')}, {line})"
        if left_type == right_type and left_type in ("int", "bool"):
            l, r = self.expr(left), self.expr(right)
            if op in INT_OPS:
                return f"{INT_OPS[op]}({l}, {r}, {line})"
            return f"({l} {op} {r})"
        # At least one side is a float: widen both and do it in doubles.
        l, r = self.convert(left, "float"), self.convert(right, "float")
        if op == "%":
            return f"ember_fmod({l}, {r}, {line})"
        return f"({l} {op} {r})"

    def call(self, call: ast.Call) -> str:
        line = call.span.line
        args = call.args
        match call.name:
            case "print":
                return f"ember_print_{self.type_of(args[0])}({self.expr(args[0])})"
            case "read_line":
                return "ember_read_line()"
            case "to_float":
                return f"ember_to_float({self.expr(args[0])}, {line})"
            case "len":
                return f"ember_len({self.expr(args[0])})"
        params = self.checked.functions[call.name].params
        converted = ", ".join(self.convert(arg, t) for arg, t in zip(args, params))
        return f"ember_fn_{call.name}({converted})"
